-- ============================================================================
-- Bachify · Migration 00002 · Core tables
-- ----------------------------------------------------------------------------
-- Identity, group and cycle structure. Financial tables live in 00003.
--
-- Identity model (Neon Auth):
--   * Neon Auth stores managed users in the neon_auth schema. That schema is
--     owned by Neon and must not be modified by application migrations.
--   * public.profiles is the application-owned identity record.
--   * profiles.auth_user_id stores the JWT `sub` claim (text) exactly as
--     returned by auth.user_id(). We do NOT assume that Neon Auth user ids are
--     UUIDs, and we do not add a foreign key into the managed schema.
--   * The unique constraint on auth_user_id is the safe, one-to-one mapping
--     between a Neon Auth user and an application profile.
--
-- Conventions used by every table in this project:
--   * uuid application primary keys generated by the database.
--   * timestamptz for every timestamp, defaulted to now().
--   * numeric(12,2) for money. Never float / double precision.
--   * Historical rows are archived or deactivated, never hard-deleted.
-- ============================================================================

-- Reusable updated_at trigger. Defined before the tables so every table can
-- attach it in the same migration.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

comment on function public.set_updated_at() is
  'Sets updated_at on row update. Attached to every mutable application table.';

-- ----------------------------------------------------------------------------
-- profiles
-- Application profile for a Neon Auth user. Role is stored here, never
-- supplied by the client on write (enforced by trigger in 00005 and RLS in
-- 00007). Profiles are created by ensure_own_profile() (00008) or by a
-- trusted operator using the direct database connection.
-- ----------------------------------------------------------------------------
create table public.profiles (
  id            uuid primary key default gen_random_uuid(),
  auth_user_id  text not null unique,
  full_name     text not null,
  phone         text,
  email         text,
  role          public.user_role not null default 'member',
  is_active     boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint profiles_auth_user_id_not_blank check (length(btrim(auth_user_id)) > 0),
  constraint profiles_full_name_not_blank check (length(btrim(full_name)) > 0)
);

comment on table public.profiles is
  'Application profile for a Neon Auth user. Holds the trusted application role.';
comment on column public.profiles.auth_user_id is
  'Neon Auth identity: the JWT sub claim as text (matches auth.user_id()). Unique and immutable.';
comment on column public.profiles.role is
  'Only an administrator may change this value (trigger + RLS).';

create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function public.set_updated_at();

-- ----------------------------------------------------------------------------
-- bhishi_groups
-- A savings group definition. Contribution amount / collection day here are
-- defaults only; a cycle snapshots them when it starts.
-- ----------------------------------------------------------------------------
create table public.bhishi_groups (
  id                   uuid primary key default gen_random_uuid(),
  name                 text not null,
  description          text,
  contribution_amount  numeric(12,2) not null,
  collection_day       integer not null default 12,
  start_date           date,
  status               public.group_status not null default 'draft',
  created_by           uuid references public.profiles (id) on delete set null,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  constraint bhishi_groups_name_not_blank check (length(btrim(name)) > 0),
  constraint bhishi_groups_contribution_positive check (contribution_amount > 0),
  constraint bhishi_groups_collection_day_range check (collection_day between 1 and 31)
);

comment on table public.bhishi_groups is
  'Bhishi group settings. Archived instead of deleted so history stays intact.';

create trigger bhishi_groups_set_updated_at
  before update on public.bhishi_groups
  for each row execute function public.set_updated_at();

-- ----------------------------------------------------------------------------
-- members
-- A person in the savings network. A member may exist without a login account,
-- so profile_id is nullable. Phone is the natural contact identifier.
-- ----------------------------------------------------------------------------
create table public.members (
  id          uuid primary key default gen_random_uuid(),
  full_name   text not null,
  phone       text,
  email       text,
  profile_id  uuid references public.profiles (id) on delete set null,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint members_full_name_not_blank check (length(btrim(full_name)) > 0)
);

comment on table public.members is
  'A person who participates in groups. profile_id is optional: not every member logs in.';

create trigger members_set_updated_at
  before update on public.members
  for each row execute function public.set_updated_at();

-- ----------------------------------------------------------------------------
-- group_members
-- Membership join table. Removing a member sets status = 'removed'; the row is
-- retained so historical cycles still resolve.
-- ----------------------------------------------------------------------------
create table public.group_members (
  id         uuid primary key default gen_random_uuid(),
  group_id   uuid not null references public.bhishi_groups (id) on delete restrict,
  member_id  uuid not null references public.members (id) on delete restrict,
  joined_at  timestamptz not null default now(),
  status     public.membership_status not null default 'active',
  constraint group_members_unique_membership unique (group_id, member_id)
);

comment on table public.group_members is
  'Membership of a member in a group. Unique per (group, member); removal is non-destructive.';

-- ----------------------------------------------------------------------------
-- cycles
-- One full rotation of payouts. Contribution amount and collection day are
-- snapshots so later edits to the group never rewrite historical cycles.
-- ----------------------------------------------------------------------------
create table public.cycles (
  id                           uuid primary key default gen_random_uuid(),
  group_id                     uuid not null references public.bhishi_groups (id) on delete restrict,
  name                         text not null,
  start_date                   date not null,
  contribution_amount_snapshot numeric(12,2) not null,
  collection_day_snapshot      integer not null,
  total_members                integer not null,
  duration_months              integer not null,
  status                       public.cycle_status not null default 'draft',
  created_at                   timestamptz not null default now(),
  updated_at                   timestamptz not null default now(),
  constraint cycles_name_not_blank check (length(btrim(name)) > 0),
  constraint cycles_contribution_snapshot_positive check (contribution_amount_snapshot > 0),
  constraint cycles_collection_day_range check (collection_day_snapshot between 1 and 31),
  constraint cycles_total_members_positive check (total_members > 0),
  constraint cycles_duration_months_positive check (duration_months > 0)
);

comment on table public.cycles is
  'One savings rotation. Contribution and collection-day values are immutable snapshots.';

create trigger cycles_set_updated_at
  before update on public.cycles
  for each row execute function public.set_updated_at();

-- ----------------------------------------------------------------------------
-- cycle_members
-- Chit order is per-cycle and independent between cycles: the same member may
-- hold a different position in a later cycle.
-- ----------------------------------------------------------------------------
create table public.cycle_members (
  id           uuid primary key default gen_random_uuid(),
  cycle_id     uuid not null references public.cycles (id) on delete restrict,
  member_id    uuid not null references public.members (id) on delete restrict,
  chit_number  integer not null,
  created_at   timestamptz not null default now(),
  constraint cycle_members_unique_member unique (cycle_id, member_id),
  constraint cycle_members_unique_chit unique (cycle_id, chit_number),
  constraint cycle_members_chit_positive check (chit_number > 0)
);

comment on table public.cycle_members is
  'Member + chit position within a single cycle. Historical orders are never overwritten.';
